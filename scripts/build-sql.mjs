// Builds the two "everything in one paste" copies of the database setup from the
// numbered files in supabase/migrations/, so there is only one place to edit:
//
//   supabase/schema.sql      what you paste into a new Supabase project
//   lib/schemaUpdateSql.ts   what the app shows (with a Copy button) when the database is behind
//
//   npm run build:sql        rewrite them after adding or changing a migration
//
// A test (lib/schema.test.ts) fails if they are out of date.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function build() {
  const dir = join(root, "supabase", "migrations");
  const files = readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
  const body = files.map((f) => `-- ===== ${f} =====\n${readFileSync(join(dir, f), "utf8").trim()}\n`).join("\n");
  const version = Number(files[files.length - 1].slice(0, 4));
  const schema =
    `-- TC Assistant database setup (generated by "npm run build:sql": edit supabase/migrations/ instead).\n` +
    `-- Paste this whole file into Supabase: SQL Editor > New query > Run.\n` +
    `-- It is safe to run more than once, on a new or an existing project.\n\n${body}`;
  const ts =
    `// Generated by "npm run build:sql" from supabase/migrations/. Do not edit by hand.\n` +
    `// This is what the app shows, with a Copy button, when the database is behind.\n` +
    `// It is safe to run more than once.\n` +
    `export const requiredSchemaVersion = ${version};\n\n` +
    `export const schemaUpdateSql = ${JSON.stringify(schema)};\n`;
  return { schema, ts };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { schema, ts } = build();
  writeFileSync(join(root, "supabase", "schema.sql"), schema);
  writeFileSync(join(root, "lib", "schemaUpdateSql.ts"), ts);
  console.log("wrote supabase/schema.sql and lib/schemaUpdateSql.ts");
}
